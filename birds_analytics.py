import re
from collections import Counter
import pymorphy3

# Ваш текст. Замените этот текст на свой.
big_text = """
Ваш большой текст на русском языке находится здесь. 
В лесу пел соловей, а над полем парил ястреб. 
Воробьи и синицы прыгали по веткам. Синиц было двое.
Где-то вдали кричала крачка. Жаворонки и овсянки прыгали где-то рядом.
"""

# Создаем список названий птиц в именительном падеже, единственном числе.
# Этот список можно и нужно расширять!
list_of_birds = [
    'аист', 'беркут', 'голубь', 'грач', 'дятел', 'жаворонок', 'ласточка', 'лебедь',
    'орёл', 'сова', 'сокол', 'сорока', 'стриж', 'цапля', 'чибис', 'чиж', 'юрок',
    'воробей', 'ворона', 'галка', 'глухарь', 'горихвостка', 'дрозд', 'дупель',
    'жаворонок', 'зимородок', 'зяблик', 'канарейка', 'клёст', 'коноплянка', 'коршун',
    'коростель', 'кукушка', 'куропатка', 'лунь', 'неясыть', 'овсянка', 'перепел',
    'пеликан', 'пингвин', 'попугай', 'пустельга', 'рябчик', 'синица', 'скворец',
    'снегирь', 'соловей', 'тетерев', 'удод', 'филин', 'чеглок', 'чирок', 'щура',
    'ястреб', 'крачка', 'чайка', 'кедровка', 'свиристель', 'вертишейка', 'кряква'
]

# Нормализуем словарь птиц (приводим к нормальной форме для надежности)
morph = pymorphy3.MorphAnalyzer()
normalized_birds_set = set()
for bird in list_of_birds:
    parsed = morph.parse(bird)[0]
    normalized_birds_set.add(parsed.normal_form)

# Приводим весь текст к нижнему регистру
text_lower = big_text.lower()

# Разбиваем текст на слова, удаляя все знаки препинания
words = re.findall(r'\b[а-яё]+\b', text_lower)

# Создаем список для найденных птиц
found_birds = []

# Анализируем каждое слово
for word in words:
    # Пропускаем слишком короткие слова
    if len(word) < 3:
        continue

    # Приводим слово к нормальной форме (им.падеж, ед.число)
    parsed_word = morph.parse(word)[0]
    normal_form = parsed_word.normal_form

    # Проверяем, есть ли это слово в нашем множестве птиц
    if normal_form in normalized_birds_set:
        found_birds.append(normal_form)  # или можно append(word) для оригинала

# Убираем дубликаты и считаем количество упоминаний
bird_counts = Counter(found_birds)

# Выводим результат
print("Найденные птицы и количество упоминаний:")
for bird, count in bird_counts.most_common():
    print(f"{bird}: {count}")

# Или просто уникальный список
print("\nУникальный список птиц:")
unique_birds = sorted(set(found_birds))
for bird in unique_birds:
    print(bird)